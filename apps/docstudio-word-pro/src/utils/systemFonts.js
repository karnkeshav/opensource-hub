export async function getSystemFonts() {
  let fonts = [...WINDOWS_SYSTEM_FONTS];

  // Modern Chromium / Electron Local Font Access API
  if (typeof window !== 'undefined' && 'queryLocalFonts' in window) {
    try {
      const localFonts = await window.queryLocalFonts();
      const localFamilies = localFonts.map(f => f.family).filter(Boolean);
      if (localFamilies.length > 0) {
        const merged = Array.from(new Set([...fonts, ...localFamilies]));
        return merged.sort((a, b) => a.localeCompare(b));
      }
    } catch (err) {
      console.warn('Local Font Access API query skipped, using full Windows system font catalog', err);
    }
  }

  return fonts.sort((a, b) => a.localeCompare(b));
}
